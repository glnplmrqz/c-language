#include<stdio.h>
#include<stdlib.h>

    int main()
    {
        printf("\n 2 + 5 = %d\n", 2 + 5);
        printf(" 13 + 89 = %d\n", 13 + 89);
        printf(" 34 - 20 = %d\n", 34 - 20);
        printf(" 45 - 90 = %d\n", 45 - 90);
        printf(" 2 * 7 = %d\n", 2 * 7);
        printf(" 5 / 2 = %d\n", 5 / 2);
        printf(" 14 / 7 = %d\n", 14 / 7);
        printf(" 34 % 5 = %d\n",34 % 5);
        printf(" 4 % 6 = %d\n", 4 % 6);

        printf("\n 5.0 + 3.5 = %.1f\n", 5.0 + 3.5);
        printf(" 3.0 + 9.4 = %.1f\n", 3.0 + 9.4);
        printf(" 16.3 - 5.2 = %.1f\n", 16.3 - 5.2);
        printf(" 4.2 * 2.5 = %.1f\n", 4.2 * 2.5);
        printf(" 5.0 / 2.0 = %.1f\n", 5.0 / 2.0);
        printf(" 34.5 / 6.0 = %.2f\n", 34.5 / 6.0);
        printf(" 34.5 / 6.5 = %.5f\n", 34.5 / 6.5);
        return 0;
    }